CREATE TABLE iam_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL
);
CREATE TABLE iam_permissions (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code VARCHAR(150) NOT NULL UNIQUE,
    resource VARCHAR(100) NOT NULL,
    action VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    UNIQUE(resource,action)
);
CREATE TABLE iam_group_member_roles (
    user_id BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL REFERENCES iam_roles(id),
    PRIMARY KEY(user_id,group_id,role_id),
    FOREIGN KEY(user_id,group_id) REFERENCES iam_group_members(user_id,group_id) ON DELETE CASCADE
);
CREATE INDEX idx_iam_member_roles_role ON iam_group_member_roles(role_id);
CREATE TABLE iam_role_permissions (
    role_id BIGINT NOT NULL REFERENCES iam_roles(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES iam_permissions(id),
    PRIMARY KEY(role_id,permission_id)
);
CREATE TABLE iam_user_permission_overrides (
    user_id BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL REFERENCES iam_permissions(id),
    effect VARCHAR(5) NOT NULL CHECK(effect IN('ALLOW','DENY')),
    expires_at TIMESTAMPTZ,
    reason VARCHAR(1000) NOT NULL,
    PRIMARY KEY(user_id,group_id,permission_id),
    FOREIGN KEY(user_id,group_id) REFERENCES iam_group_members(user_id,group_id) ON DELETE CASCADE
);
CREATE INDEX idx_iam_override_expiry ON iam_user_permission_overrides(expires_at);
CREATE TABLE iam_permission_audit_logs (
